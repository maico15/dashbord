-- Форма ответа повторяет GET /api/gantt один в один.
create or replace function public.gantt_board()
returns json
language sql
stable
security definer
set search_path = public
as $$
  select json_build_object('engineers', coalesce(json_agg(e order by e.id), '[]'::json))
  from (
    select
      m.id,
      m.name,
      m.avatar_color as color,
      coalesce(v.hidden, false) as hidden,
      (select max(d.report_date) from public.daily_reports d
        where d.engineer_id = m.id) as latest_report_date,
      (select (dr.next_tasks::json ->> 0)
         from public.daily_reports dr
        where dr.engineer_id = m.id
        order by dr.report_date desc
        limit 1) as suggested_next,
      coalesce((
        select json_agg(to_json(a) order by a.start_date)
          from public.gantt_assignments a
         where a.engineer_id = m.id
      ), '[]'::json) as assignments
    from public.team_members m
    left join public.gantt_visibility v on v.engineer_id = m.id
  ) e;
$$;

-- Форма ответа повторяет GET /api/backlog.
create or replace function public.backlog_board()
returns json
language sql
stable
security definer
set search_path = public
as $$
  select json_build_object(
    'items', coalesce((
      select json_agg(to_json(b) order by
        case b.priority
          when 'P0' then 0 when 'P1' then 1 when 'P2' then 2
          when 'ENABLER' then 3 when 'GATED' then 4 else 2 end,
        b.sort_order, b.id)
      from public.backlog_items b
    ), '[]'::json),
    'sheet_url', (select value from public.config where key = 'backlog_sheet_csv_url'),
    'last_sync', (select value from public.config where key = 'last_backlog_sync')
  );
$$;

-- Любой номер IT- → то единственное место, где он живёт.
-- Ветка IT-заявок добавится вместе с разделом IT request.
create or replace function public.lookup_ref(p_ref text)
returns json
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  n         integer;
  canonical text;
  hit       record;
  pct       integer;
begin
  n := (substring(upper(p_ref) from 'IT-?0*([0-9]+)'))::integer;
  if n is null then
    raise exception 'Ожидался номер вида IT-0162';
  end if;
  canonical := 'IT-' || lpad(n::text, 4, '0');

  select g.id, g.project as title, g.status, g.percent, t.name as engineer
    into hit
    from public.gantt_assignments g
    left join public.team_members t on t.id = g.engineer_id
   where g.ref = canonical;

  if found then
    return json_build_object(
      'ref', canonical, 'kind', 'gantt', 'id', hit.id, 'title', hit.title,
      'engineer', coalesce(hit.engineer, ''), 'status', hit.status,
      'percent', hit.percent, 'url', '/team-gantt?ref=' || canonical);
  end if;

  select b.id, b.title, b.owner, b.status, b.description
    into hit
    from public.backlog_items b
   where b.ref = canonical;

  if found then
    -- Процент, с которым задача ушла с доски, записан в строке «Снято с Ганта».
    -- Строк может быть несколько (задача ездила туда-обратно) — нужна последняя.
    select m[1]::integer into pct
      from regexp_matches(hit.description,
             E'Снято с Ганта [^\n]*, было ([0-9]{1,3})% у', 'g')
             with ordinality as t(m, ord)
     order by t.ord desc
     limit 1;

    return json_build_object(
      'ref', canonical, 'kind', 'backlog', 'id', hit.id, 'title', hit.title,
      'engineer', coalesce(hit.owner, ''),
      'status', coalesce(nullif(hit.status, ''), 'backlog'),
      'percent', pct, 'url', '/team-gantt?ref=' || canonical);
  end if;

  raise exception '% не найден', canonical;
end $$;

-- ------------------------------------------------------------- запись --

-- Снять задачу с Ганта в бэклог. Номер IT- едет вместе с ней, заметка
-- становится описанием, и к описанию дописывается строка с датой, процентом,
-- инженером и причиной. Обратный ход (назначить из бэклога) читает процент
-- из этой строки и убирает её.
create or replace function public.gantt_to_backlog(
  p_assignment_id bigint,
  p_reason        text
)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  task        record;
  reason      text;
  engineer    text;
  pct         integer;
  line        text;
  note        text;
  descr       text;
  prio        text;
  next_order  integer;
  new_id      bigint;
begin
  -- Причина обязательна: задача, ушедшая из плана без причины, — это то, как
  -- работа теряется.
  reason := btrim(regexp_replace(coalesce(p_reason, ''), '\s+', ' ', 'g'));
  if reason = '' then
    raise exception 'Нужна причина';
  end if;

  select g.*, t.name as engineer_name
    into task
    from public.gantt_assignments g
    left join public.team_members t on t.id = g.engineer_id
   where g.id = p_assignment_id;

  if not found then
    raise exception 'Задача на Ганте не найдена';
  end if;

  engineer := coalesce(task.engineer_name, '');
  pct      := greatest(0, least(100, coalesce(task.percent, 0)));
  line     := 'Снято с Ганта ' || to_char(now() at time zone 'utc', 'YYYY-MM-DD')
              || ', было ' || pct || '% у ' || coalesce(nullif(engineer, ''), '—')
              || '. Причина: ' || reason || '.';
  note     := rtrim(coalesce(task.note, ''));
  descr    := case when note = '' then line else note || chr(10) || chr(10) || line end;
  prio     := case when task.priority in ('P0','P1','P2','ENABLER','GATED')
                   then task.priority else 'P2' end;

  select coalesce(max(sort_order), 0) + 1 into next_order from public.backlog_items;

  insert into public.backlog_items
    (ref, title, description, owner, priority, est_days, sort_order, created_at)
  values
    (coalesce(task.ref, public.allocate_ref()), task.project, descr, engineer,
     prio, coalesce(task.est_days, 10), next_order,
     to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS'))
  returning id into new_id;

  -- Иначе зависимая задача будет показывать на строку, которой больше нет.
  update public.gantt_assignments set depends_on = null where depends_on = p_assignment_id;
  delete from public.gantt_assignments where id = p_assignment_id;

  return (select to_json(b) from public.backlog_items b where b.id = new_id);
end $$;

