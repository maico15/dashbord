-- ============================================================================
-- Гант: схема для Supabase. Первый раздел переезда.
--
-- Что здесь есть:
--   * таблицы, на которых стоит доска, бэклог и единая нумерация IT-;
--   * функции чтения, отдающие ровно ту же форму ответа, что нынешний FastAPI
--     (src/data/gantt.rest.js — эталон формата);
--   * функции записи, которым важна атомарность: выдача номера IT- и перенос
--     задачи с доски в бэклог.
--
-- Чего здесь сознательно нет:
--   * gantt_apply_changes — очередь правок с доски. Девять типов изменений со
--     ссылками на временные id внутри одной пачки. Это самая ценная и самая
--     хрупкая часть доски, и переносить её надо построчно по питоновскому
--     коду и с проверкой, а не переписывать по памяти. Заглушка ниже честно
--     падает с объяснением, а не делает вид, что сохранила.
--   * два синка (проценты из ежедневных отчётов, бэклог из Google-таблицы) —
--     они ходят во внешние системы и станут edge-функциями.
--   * ветка IT-заявок в lookup_ref — она появится вместе с разделом IT request.
--
-- Данные эта миграция не переносит: она создаёт пустую схему. Перенос строк
-- из нынешней базы — отдельный шаг, после того как схема принята.
-- ============================================================================

-- ---------------------------------------------------------------- таблицы --

create table if not exists public.team_members (
  id            bigint generated by default as identity primary key,
  name          text not null,
  stream        text not null default 'dev',
  avatar_color  text default '#00cfff',
  position      text default '',
  email         text default '',
  department_id bigint default 1
);

create table if not exists public.gantt_assignments (
  id          bigint generated by default as identity primary key,
  engineer_id bigint not null references public.team_members(id) on delete cascade,
  project     text not null,
  start_date  text not null,              -- календарный день, YYYY-MM-DD
  est_days    integer not null default 10,
  percent     integer not null default 0,
  status      text not null default 'active'
              check (status in ('active','queued','continuous','done')),
  queue_start text,
  note        text default '',
  depends_on  bigint references public.gantt_assignments(id) on delete set null,
  ref         text unique,                -- IT-0162, выдаётся один раз и не меняется
  priority    text default '',            -- живёт только чтобы пережить поездку в бэклог
  updated_at  text
);

create index if not exists gantt_assignments_engineer_idx
  on public.gantt_assignments (engineer_id, start_date);

create table if not exists public.gantt_visibility (
  engineer_id bigint primary key references public.team_members(id) on delete cascade,
  hidden      boolean not null default false
);

create table if not exists public.backlog_items (
  id          bigint generated by default as identity primary key,
  ref         text unique,
  title       text not null,
  description text default '',
  owner       text default '',
  priority    text default 'P2',
  est_days    integer default 10,
  est_hours   real,
  roi         text default '',
  cost        text default '',
  ret         text default '',
  status      text default '',
  source      text default '',
  origin      text default '',
  sort_order  integer default 0,
  created_at  text
);

create table if not exists public.config (
  key   text primary key,
  value text
);

-- Доска показывает дату последнего отчёта инженера и подсказку «что дальше».
-- Полная таблица приедет вместе с разделом Daily Report; здесь ровно те
-- колонки, которые читает Гант.
create table if not exists public.daily_reports (
  id          bigint generated by default as identity primary key,
  engineer_id bigint references public.team_members(id) on delete cascade,
  report_date text not null,
  next_tasks  text default '[]',          -- JSON-массив строк
  unique (engineer_id, report_date)
);

-- Единая нумерация IT-. Одна строка, одно место, где номер рождается.
create table if not exists public.ref_counter (
  id         integer primary key check (id = 1),
  next_value integer not null
);

insert into public.ref_counter (id, next_value)
values (1, 1)
on conflict (id) do nothing;

-- ---------------------------------------------------------------- доступ --
--
-- Сегодня чтение доски публично, а запись защищена паролем администратора в
-- query-параметре. Здесь это выражено честнее: читать таблицы может кто
-- угодно с anon-ключом, писать — никто напрямую. Любая запись идёт через
-- функции ниже (security definer), то есть через проверку.

alter table public.team_members      enable row level security;
alter table public.gantt_assignments enable row level security;
alter table public.gantt_visibility  enable row level security;
alter table public.backlog_items     enable row level security;
alter table public.daily_reports     enable row level security;
alter table public.ref_counter       enable row level security;
alter table public.config            enable row level security;

do $$
declare t text;
begin
  foreach t in array array['team_members','gantt_assignments','gantt_visibility',
                           'backlog_items','daily_reports']
  loop
    execute format(
      'drop policy if exists %I on public.%I', t || '_read', t);
    execute format(
      'create policy %I on public.%I for select using (true)', t || '_read', t);
  end loop;
end $$;

-- config и ref_counter не читаются напрямую: в config лежат ключи интеграций,
-- а счётчик имеет смысл только внутри allocate_ref. Политик select у них нет.

-- -------------------------------------------------------------- нумерация --

create or replace function public.allocate_ref()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare n integer;
begin
  -- Один UPDATE … RETURNING: двум одновременным вызовам один номер достаться
  -- не может, Postgres держит строку счётчика до конца транзакции. Номера
  -- назад не отдаются — откатившийся вызов просто оставляет дырку.
  update public.ref_counter
     set next_value = next_value + 1
   where id = 1
  returning next_value - 1 into n;

  if n is null then
    raise exception 'ref_counter не инициализирован';
  end if;

  return 'IT-' || lpad(n::text, 4, '0');
end $$;

-- Поднять счётчик выше самого большого уже занятого номера. Запускается после
-- переноса данных, иначе первый же новый номер окажется занятым.
create or replace function public.bump_ref_counter()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare floor_value integer;
begin
  select coalesce(max(n), 0) + 1 into floor_value
  from (
    select (substring(ref from 'IT-([0-9]+)'))::integer as n
      from public.gantt_assignments where ref is not null
    union all
    select (substring(ref from 'IT-([0-9]+)'))::integer
      from public.backlog_items where ref is not null
  ) all_refs;

  update public.ref_counter
     set next_value = floor_value
   where id = 1 and next_value < floor_value;

  return floor_value;
end $$;

