-- ------------------------------------------------------------- служебное --

create or replace function public.verify_admin_password(p_password text)
returns json
language plpgsql
stable
security definer
set search_path = public
as $$
declare stored text;
begin
  select value into stored from public.config where key = 'admin_password';
  if stored is null or stored <> p_password then
    raise exception 'Неверный пароль';
  end if;
  return json_build_object('ok', true);
end $$;

create or replace function public.health()
returns json
language sql
stable
as $$ select json_build_object('ok', true); $$;

