/* Слой данных.
 *
 * Страницы ходят только сюда и не знают, где лежат данные. Какая реализация
 * работает, решает одна переменная окружения VITE_DATA_SOURCE:
 *
 *   rest      — нынешний FastAPI на Render (по умолчанию)
 *   supabase  — проект Supabase
 *
 * Весь переезд базы — это смена этого значения. Ни одна строка в самой
 * странице Ганта при этом не меняется, поэтому откат стоит столько же,
 * сколько переезд, и его можно сделать в любой момент.
 *
 * Обе реализации обязаны возвращать одинаковые структуры. Что именно они
 * возвращают, описано в gantt.rest.js — он эталон, потому что его формат
 * сегодня работает в проде.
 */

import * as rest from './gantt.rest'
import * as supabase from './gantt.supabase'

const SOURCE = import.meta.env.VITE_DATA_SOURCE || 'rest'

export const gantt = SOURCE === 'supabase' ? supabase : rest

/** Чтобы на странице можно было показать, откуда читаются данные. */
export const DATA_SOURCE = SOURCE
